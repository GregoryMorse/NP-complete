#!/usr/bin/env python3
"""Generate formal/ZP/Table.lean from machines/<name>.tbl (python3 formal/gen_table.py).

Transition code: 0 = undefined, otherwise 1 + w + 2*d + 4*next with d = 1 for a
right move.  CI regenerates the file and fails if it differs from the commit.
"""
import hashlib, json, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def lean_table(name, ident):
    lines = open(os.path.join(ROOT, 'machines', name + '.tbl')).read().split('\n')
    n, beep = map(int, lines[0].split())
    meta = json.load(open(os.path.join(ROOT, 'machines', name + '.json')))
    rows = []
    for q in range(n):
        f = list(map(int, lines[1 + q].split()))
        codes = []
        for w, d, nxt in (f[0:3], f[3:6]):
            codes.append(0 if nxt < 0 else 1 + w + 2 * d + 4 * nxt)
        rows.append(f'({codes[0]}, {codes[1]})')
    # one definition per 32-row chunk keeps every literal small for the elaborator
    chunks = [rows[i:i + 32] for i in range(0, n, 32)]
    out = []
    for c, ch in enumerate(chunks):
        out.append(f'def {ident}Rows{c} : List (Nat × Nat) :=\n  [' + ',\n   '.join(ch) + ']\n')
    out.append(f'/-- `machines/{name}.txt` ({n} states, beep state {beep}, SHA-256 of the')
    out.append(f'standard text {meta["sha256"]}). Row q is (code on 0, code on 1). -/')
    out.append(f'def {ident}Table : List (Nat × Nat) :=')
    out.append('  ' + ' ++\n  '.join(f'{ident}Rows{c}' for c in range(len(chunks))))
    out.append(f'\n/-- {name} as a machine with its designated beep state. -/')
    out.append(f'def {ident} : TM := ⟨{ident}Table, {beep}⟩\n')
    return '\n'.join(out), n


TABLES = {
    # machines/ name: (Lean identifier, file suffix)
    'zp_native': ('zpMachine', ''),
    'zpp_native': ('zppMachine', 'PP'),
    'zps_native': ('zpsMachine', 'PS'),
    'zfactor_native': ('zfacMachine', 'F'),
    'zdlog_native': ('zdlMachine', 'D'),
    'zgi_native': ('zgiMachine', 'G'),
    'zntt_native': ('znttMachine', 'NTT'),
    'twinprime_native': ('twinMachine', 'Twin'),
    'zconp_native': ('zconpMachine', 'Conp'),
    'zmul_native': ('zmulMachine', 'Mul'),
}


def main(name='zp_native'):
    ident, suf = TABLES[name]
    body, n = lean_table(name, ident)
    text = ('module\n\npublic import ZP.Defs\n\n@[expose] public section\n\n'
            f'/-! Generated by `formal/gen_table.py{"" if suf == "" else " " + name}` from `machines/{name}.tbl`; do not edit. -/\n\n'
            'namespace ZP\n\n' + body + '\nend ZP\n')
    path = os.path.join(ROOT, 'formal', 'ZP', 'Table' + suf + '.lean')
    open(path, 'w').write(text)
    print(path, n, 'states')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'zp_native')
