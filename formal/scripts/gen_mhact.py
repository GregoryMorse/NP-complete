"""Generate ZP/MHActSeg.lean: the segments of the multihead act (python3 formal/scripts/gen_mhact.py > ZP/MHActSeg.lean).

Tape of an act, from `G2 w d` (right of `H`) to `RTW`:

    Qc 0^g 0 c H  Y  B  <storage>        Y = M_g .. end of the fuel (no blank), B = the blank after the fuel

The storage is `P B T` with the marker `B` of the current head.  The loops of `G2`/`G3` (skip to the marker),
the four operations and the read/carry back to `RTW` are separate segments."""
import seggen
from seggen import Var

G = seggen.Gen('mhBase', rows='mhBase', logic='LogicBaseMH', qfiles=['LogicBaseMH'], nsmap={'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.MHSeg

@[expose] public section

/-!
# Multihead act: segments (generated)

Generated by `formal/scripts/gen_mhact.py`; do not edit. The tape of an act is

    Qc 0^g 0 c H  Y  B  S                  (Y = `M_g ... end of fuel`, no blank; `S` = the storage)

with `S = P B T`, `B` the marker of the current head. `act*` segments go from `G2 w d` on the first
cell of `Y` (the head is right of `H`) to `RR` right of the new marker (or `KB` for a clamped move);
`carry*` segments finish: they read the scanned symbol and write it into `c`, ending in `RTW` on the
last cell of `Qc`. All statements are about `mhBase`; they transfer to every machine that extends it.
-/

namespace ZP.MH

open ZP

'''


def out(s):
    print(s)


def vs_common(extra=()):
    return [Var('Qc', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('Y', 'list', 'NB', hyp='hY')] + list(extra)


def main():
    print(HEAD)
    pre = 'Qc g B B M'
    ll = lambda s: '%s %s' % (pre, s)
    bnd = '(Qc Y {ex} : List Nat) (g {nx} : Nat) {hx}(hQ : Bits Qc) (hY : NoB Y) {hh}'
    # ---- right ----
    out(G.theorem('actMR', 'Move right on a bit `b`: the marker swaps with it; `RR` right of the new marker.',
        '(Qc Y P T : List Nat) (g b : Nat) (hb : b ∈ bits) (hQ : Bits Qc) (hY : NoB Y) (hP : NoB P) (hT : Sym4 T)',
        vs_common([Var('P', 'list', 'NB', hyp='hP'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G211', False, pre, 'Y B P B $b T'), ('RR', False, ll('Y B P $b B'), 'T'),
        cases=[('b', [2, 3], 'hb')]))
    out(G.theorem('actMR0', 'Move right at the end of the unit (nothing right of the marker): `KB`.',
        '(Qc Y P : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hP : NoB P)',
        vs_common([Var('P', 'list', 'NB', hyp='hP')]),
        ('G211', False, pre, 'Y B P B'), ('KB', True, ll('Y B P'), 'B')))
    out(G.theorem('actMR1', 'Move right at the end of the unit (next unit follows): `KB`.',
        '(Qc Y P T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hP : NoB P) (hT : Sym4 T)',
        vs_common([Var('P', 'list', 'NB', hyp='hP'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G211', False, pre, 'Y B P B M T'), ('KB', True, ll('Y B P'), 'B M T')))
    # ---- left ----
    out(G.theorem('actML', 'Move left over a bit `a`: the marker swaps with it; `RR` on the moved bit.',
        '(Qc Y P T : List Nat) (g a : Nat) (ha : a ∈ bits) (hQ : Bits Qc) (hY : NoB Y) (hP : NoB P) (hT : Sym4 T)',
        vs_common([Var('P', 'list', 'NB', hyp='hP'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G210', False, pre, 'Y B P $a B T'), ('RR', False, ll('Y B P B'), '$a T'),
        cases=[('a', [2, 3], 'ha')]))
    out(G.theorem('actML0', 'Move left at the unit start (the scanned cell is `M`): `KB`.',
        '(Qc Y P T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hP : NoB P) (hT : Sym4 T)',
        vs_common([Var('P', 'list', 'NB', hyp='hP'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G210', False, pre, 'Y B P M B T'), ('KB', True, ll('Y B P'), 'M B T')))
    # ---- next head (the unit to the left) ----
    out(G.theorem('actLS', 'Next head: the unit to the left; its marker becomes the current one.',
        '(Qc Y SL N Lb T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hS : NoB SL) (hN : Bits N) (hL : Bits Lb) '
        '(hT : Sym4 T)',
        vs_common([Var('SL', 'list', 'NB', hyp='hS'), Var('N', 'list', 'bits', hyp='hN'),
                   Var('Lb', 'list', 'bits', hyp='hL'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G201', False, pre, 'Y B SL M N M Lb B T'), ('RR', False, ll('Y B SL B'), 'N M Lb M T')))
    out(G.theorem('actLS0', 'Next head at the leftmost unit: the marker stays.',
        '(Qc Y Lb T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hL : Bits Lb) (hT : Sym4 T)',
        vs_common([Var('Lb', 'list', 'bits', hyp='hL'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('G201', False, pre, 'Y B M Lb B T'), ('RR', False, ll('Y B M Lb B'), 'T')))
    # ---- previous head (the unit to the right) ----
    out(G.theorem('actRS', 'Previous head: the unit to the right; its marker becomes the current one.',
        '(Qc Y SL Lb Rp N T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hS : NoB SL) (hL : Bits Lb) '
        '(hR : Bits Rp) (hN : Bits N) (hT : Sym4 T)',
        vs_common([Var('SL', 'list', 'NB', hyp='hS'), Var('Lb', 'list', 'bits', hyp='hL'),
                   Var('Rp', 'list', 'bits', hyp='hR'), Var('N', 'list', 'bits', hyp='hN'),
                   Var('T', 'list', 'ALL', hyp='hT')]),
        ('G200', False, pre, 'Y B SL M Lb B Rp M N M T'), ('RR', False, ll('Y B SL M Lb M Rp M N B'), 'T')))
    out(G.theorem('actRS0', 'Previous head at the rightmost unit: the marker stays.',
        '(Qc Y SL Lb Rp : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hS : NoB SL) (hL : Bits Lb) (hR : Bits Rp)',
        vs_common([Var('SL', 'list', 'NB', hyp='hS'), Var('Lb', 'list', 'bits', hyp='hL'),
                   Var('Rp', 'list', 'bits', hyp='hR')]),
        ('G200', False, pre, 'Y B SL M Lb B Rp'), ('RR', False, ll('Y B SL M Lb B'), 'Rp')))
    # ---- carry: read the scanned symbol and write it into c ----
    out(G.theorem('carryK', 'Scanned symbol `none` (or after `KB`): back to `RTW`, `c` stays blank.',
        '(Qc Y Z R : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hZ : NoB Z) (hR : Sym4 R)',
        vs_common([Var('Z', 'list', 'NB', hyp='hZ'), Var('R', 'list', 'ALL', hyp='hR')]),
        ('KB', True, ll('Y B Z'), 'R'), ('RTW', True, 'Qc', 'g B B M Y B Z R')))
    out(G.theorem('carryA', 'Scanned bit `a`, next cell a bit: write `a` into `c`.',
        '(Qc Y X T : List Nat) (g a e : Nat) (ha : a ∈ bits) (he : e ∈ bits) (hQ : Bits Qc) (hY : NoB Y) (hX : NoB X) '
        '(hT : Sym4 T)',
        vs_common([Var('X', 'list', 'NB', hyp='hX'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('RR', False, ll('Y B X $a B'), '$e T'), ('RTW', True, 'Qc', 'g B $a M Y B X $a B $e T'),
        cases=[('a', [2, 3], 'ha'), ('e', [2, 3], 'he')]))
    out(G.theorem('carryM', 'Scanned `M` (unit start), next cell a bit: `c` stays blank.',
        '(Qc Y X T : List Nat) (g e : Nat) (he : e ∈ bits) (hQ : Bits Qc) (hY : NoB Y) (hX : NoB X) (hT : Sym4 T)',
        vs_common([Var('X', 'list', 'NB', hyp='hX'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('RR', False, ll('Y B X M B'), '$e T'), ('RTW', True, 'Qc', 'g B B M Y B X M B $e T'),
        cases=[('e', [2, 3], 'he')]))
    out(G.theorem('carryN0', 'Nothing right of the marker: `c` stays blank.',
        '(Qc Y X : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hX : NoB X)',
        vs_common([Var('X', 'list', 'NB', hyp='hX')]),
        ('RR', False, ll('Y B X B'), ''), ('RTW', True, 'Qc', 'g B B M Y B X B')))
    out(G.theorem('carryN1', 'Next unit right of the marker: `c` stays blank.',
        '(Qc Y X T : List Nat) (g : Nat) (hQ : Bits Qc) (hY : NoB Y) (hX : NoB X) (hT : Sym4 T)',
        vs_common([Var('X', 'list', 'NB', hyp='hX'), Var('T', 'list', 'ALL', hyp='hT')]),
        ('RR', False, ll('Y B X B'), 'M T'), ('RTW', True, 'Qc', 'g B B M Y B X B M T')))


if __name__ == '__main__':
    main()
