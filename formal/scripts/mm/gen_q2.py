"""Generates ZP/MMQ2.lean: one iteration of the Q pass (qIter2, qIter3, qIter0) and the loop lemmas.

Invariant S(k, Wl, Os, e, Rest) at Q2 (hd form, head on the last cell of U = replicate k 2):
  hd Q2 (A ++ U) (0 :: Wl ++ 1 :: (Os ++ e :: Rest)),
`Wl` = loaded bits (above the blank), `Os` = unconsumed out cells (the last one is taken),
`e` in {0, 1}: a consumed blank or `M_g`."""
