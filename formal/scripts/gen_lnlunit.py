"""Generate ZP/LNLUnitSeg.lean: the decider setup segments of `zlnl` (walker with units, copy of one unit,
dispatch and erase).  python3 formal/scripts/gen_lnlunit.py > ZP/LNLUnitSeg.lean"""
import seggen
from seggen import Var

G = seggen.Gen('zlnlLogic', rows='zlnlLogic', logic='LogicLNL', qfiles=['LogicLNL', 'LogicBaseMH'],
               nsmap={'LogicLNL': 'QLNL', 'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.PairLNLV

@[expose] public section

/-!
# `Z_LNL` decider setup: segments (generated)

Generated by `formal/scripts/gen_lnlunit.py`; do not edit. The walker of the decider fuel (`DW*`, `WB*`) appends
one unit of the multihead storage after each block (`U0` ... `UDW`); `walkEnd` writes `H` and starts the code copy.
-/

namespace ZP.MH

open ZP

'''


def V(n, s='bits'):
    return Var(n, 'list', s, hyp='h' + n)


HB = {'bits': 'Bits', 'NB': 'NoB', 'ALL': 'Sym4'}


def binders(vs, extra=''):
    out = []
    for v in vs:
        if v.sset in HB:
            out.append('(%s : List Nat) (h%s : %s %s)' % (v.name, v.name, HB[v.sset], v.name))
        else:
            out.append('(%s : List Nat) (h%s : ∀ a ∈ %s, a ∈ %s)' % (v.name, v.name, v.name, v.sset))
    return ' '.join(out) + extra


def out(s):
    print(s.replace('wsimp', 'osimp'))


def main():
    print(HEAD)
    # ---- the last decider fuel block, then the walker turns round (units)
    vs = [V('Jl'), V('s'), V('t', 'T3'), V('Bl', 'O13')]
    out(G.theorem('blkDecLastL', 'Last decider fuel block: the walker is home at the right end, units start.',
                  binders(vs), vs,
                  ('COPY', False, 'Jl M M s', 'M M t M Bl M s@3'),
                  ('U0', False, 'Jl M M', 's M M t M Bl M s@3 1')))
    # ---- skip over cells in U0
    vs = [Var('L', 'list', 'ALL', hyp='hL'), V('Y1', 'NB'), V('Y2', 'ALL')]
    out(G.theorem('u0skip', 'The `U0` loop over non-blank cells.', binders(vs), vs,
                  ('U0', False, 'L', 'Y1 Y2'), ('U0', False, 'L Y1', 'Y2')))
    # ---- unit append
    vs = [V('Jl'), V('Jr'), V('s'), V('Y', 'NB'), V('Su', 'NB'), V('ur')]
    out(G.theorem('unitA1', 'Append a unit, nonempty store: the old marker becomes `M`, the new unit is `M M`.',
                  '(a : Nat) (ha : a ∈ bits) ' + binders(vs), vs,
                  ('U0', False, 'Jl M Jr M', 's M Y B Su M B $a ur'),
                  ('UCP', False, 'Jl M Jr M', 's M Y B Su M M $a ur M M'),
                  cases=[('a', [2, 3], 'ha')]))
    vs = [V('Jl'), V('Jr'), V('s'), V('Y', 'NB')]
    out(G.theorem('unitA0', 'Append a unit, empty store.', binders(vs), vs,
                  ('U0', False, 'Jl M Jr M', 's M Y B'),
                  ('UCP', False, 'Jl M Jr M', 's M Y B M M')))
    vs = [V('Jl'), V('Jr'), V('s1'), V('s2'), V('Y', 'NB'), V('Z0', 'NB'), V('ud')]
    out(G.theorem('ucpBody', 'Copy one bit of `s` into the new unit.',
                  '(b : Nat) (hb : b ∈ bits) ' + binders(vs), vs,
                  ('UCP', False, 'Jl M Jr M s1', '$b s2 M Y B Z0 M M ud'),
                  ('UCP', False, 'Jl M Jr M s1 $b', 's2 M Y B Z0 M M ud $b'),
                  cases=[('b', [2, 3], 'hb')]))
    vs = [V('Jl'), V('Jr'), V('s'), V('Y', 'NB'), V('Z0', 'NB'), V('ud')]
    out(G.theorem('unitC', 'The unit is complete: its marker becomes current, return to the left end.',
                  binders(vs), vs,
                  ('UCP', False, 'Jl M Jr M s', 'M Y B Z0 M M ud'),
                  ('UDW', False, '', 'Jl M Jr M s M Y B Z0 M B ud 0')))
    # ---- the walker steps back
    vs = [V('Jl'), V('Jr'), V('s'), V('Y', 'NB'), Var('Z', 'list', 'ALL', hyp='hZ')]
    out(G.theorem('walkB', 'The walker steps left over one bit.',
                  '(b : Nat) (hb : b ∈ bits) ' + binders(vs), vs,
                  ('UDW', False, '', 'Jl $b M Jr M s M Y B Z'),
                  ('U0', False, 'Jl M $b', 'Jr M s M Y B Z'),
                  cases=[('b', [2, 3], 'hb')]))
    vs = [V('Jr'), V('s'), V('Y', 'NB'), Var('Z', 'list', 'ALL', hyp='hZ')]
    out(G.theorem('walkEnd', 'The walker is home: write `H`, skip `s` and start the code copy.',
                  binders(vs), vs,
                  ('UDW', False, '', 'M Jr M s M Y B Z'),
                  ('QC', True, 'M M M Jr', 'M s M Y B Z')))
    # ---- dispatch of the decider's result (the fuel and the storage are not read)
    vs = [V('j'), V('s'), V('Fu', 'ALL')]
    for nm, st, tf, end, doc in [
            ('dOk1L', 'DP11', '1 ', ('EAs', True, 'M j M s M M', '1 M Fu'), 'Accepted, flag 1: erase.'),
            ('dOk0L', 'DP10', '', ('EAs', True, 'M j M s M M', 'M Fu'), 'Rejected, flag 0: erase.'),
            ('dBad1L', 'DP11', '', ('BEEP', True, 'M j M s M M', 'M Fu'), 'Accepted, flag 0: beep.'),
            ('dBad0L', 'DP10', '1 ', ('BEEP', True, 'M j M s M M', '1 M Fu'), 'Rejected, flag 1: beep.')]:
        out(G.theorem(nm, doc, binders(vs), vs, (st, False, 'M', 'j M s M M %sM Fu' % tf), end))
    # ---- erase the fuel and the storage: `A B M X B Y`
    vs = [Var('L', 'list', 'ALL', hyp='hL'), V('A', 'NB'), V('X', 'NB')]
    out(G.theorem('erOk0', 'Erase (storage ends at its marker), the head on the cell before `A`.', binders(vs), vs,
                  ('EAs', True, 'L M', 'A B M X B'), ('EBs', True, 'L B A@0 B B X@0 B', '')))
    out(G.theorem('erBad0', 'Erase after the beep mark.', binders(vs), vs,
                  ('EAs', False, 'L 0', 'A B M X B'), ('EBs', True, 'L 0 A@0 B B X@0 B', '')))
    vs = [Var('L', 'list', 'ALL', hyp='hL'), V('A', 'NB'), V('X', 'NB'), V('Y1', 'NB')]
    out(G.theorem('erOk1', 'Erase (the storage goes on after its marker).', '(y : Nat) (hy : y ∈ NB) ' + binders(vs), vs,
                  ('EAs', True, 'L M', 'A B M X B $y Y1'), ('EBs', True, 'L B A@0 B B X@0 B B Y1@0 B', ''),
                  cases=[('y', [1, 2, 3], 'hy')]))
    out(G.theorem('erBad1', 'Erase after the beep mark (the storage goes on after its marker).',
                  '(y : Nat) (hy : y ∈ NB) ' + binders(vs), vs,
                  ('EAs', False, 'L 0', 'A B M X B $y Y1'), ('EBs', True, 'L 0 A@0 B B X@0 B B Y1@0 B', ''),
                  cases=[('y', [1, 2, 3], 'hy')]))
    # ---- back over the erased cells
    vs = [V('j'), V('s'), Var('N', 'zeros')]
    out(G.theorem('ebsOk', 'Back over the erased cells to `M_2`.', '(j s : List Nat) (hj : Bits j) (hs : Bits s) (N : Nat)',
                  vs, ('EBs', True, 'M j M s M B N', ''), ('SINC', True, 'M j M s', '')))
    out(G.theorem('ebsBad', 'Back over the erased cells; `M_2`, `s` are erased, `J` is next.',
                  '(j s : List Nat) (hj : Bits j) (hs : Bits s) (N : Nat)',
                  vs, ('EBs', True, 'M j M s M 0 B N', ''), ('JINC', True, 'M j', 'M s->B B B B N->B')))
    import re
    pair = open('ZP/Pair.lean').read()
    m = re.search(r'((?:/--[^\n]*-/\n)?theorem blkDecStep .*?)\n\n', pair, re.S)
    print(m.group(1).replace('zpLogic', 'zlnlLogic').replace('theorem blkDecStep ', 'theorem blkDecStepL ') + '\n')
    print('end ZP.MH')


if __name__ == '__main__':
    main()
