"""Generate ZP/MHUnitSeg.lean: the segments of the unit append and the walker with units
(python3 formal/scripts/gen_mhunits.py > ZP/MHUnitSeg.lean).

Unit append (entered at `U0` right of the walker, anywhere left of the blank that separates the fuel from
the storage):  tape  `Jl M Jr M s M Mid B S`  with the storage `S` empty or `Ul M B c u2`
(the last unit `M B u`, the marker blank is the current head).  The old marker becomes `M`, the new unit
`M B s 0` is written at the far right (a copy loop over `s` that blanks and restores each bit), and the
head returns to the far left (`UDW`)."""
import seggen
from seggen import Var

G = seggen.Gen('mhBase', rows='mhBase', logic='LogicBaseMH', qfiles=['LogicBaseMH'], nsmap={'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.MHRun

@[expose] public section

/-!
# Multihead units: segments (generated)

Generated by `formal/scripts/gen_mhunits.py`; do not edit. Statements about `mhBase`.
-/

namespace ZP.MH

open ZP

'''


def main():
    print(HEAD)
    L = Var('L', 'list', 'ALL', hyp='hL')
    Rt = Var('Rt', 'list', 'NB', hyp='hRt')
    Ul = Var('Ul', 'list', 'NB', hyp='hUl')
    u2 = Var('u2', 'list', 'bits', hyp='hu2')
    print(G.theorem('uA1n', 'Unit append, first pass (storage not empty): the old marker becomes `M`; the new unit starts.',
        '(L Rt Ul u2 : List Nat) (c : Nat) (hc : c ∈ bits) (hL : Sym4 L) (hRt : NoB Rt) (hUl : NoB Ul) (hu2 : Bits u2)',
        [L, Rt, Ul, u2],
        ('U0', False, 'L', 'Rt B Ul M B $c u2'), ('U5', True, 'L Rt B Ul M M $c u2 M', 'M'),
        cases=[('c', [2, 3], 'hc')]))
    print(G.theorem('uA1e', 'Unit append, first pass (empty storage).',
        '(L Rt : List Nat) (hL : Sym4 L) (hRt : NoB Rt)',
        [L, Rt],
        ('U0', False, 'L', 'Rt B'), ('U5', True, 'L Rt B M', 'M')))
    vs = [Var('Jl', 'list', 'bits', hyp='hJl'), Var('Jr', 'list', 'bits', hyp='hJr'),
          Var('s', 'list', 'bits', hyp='hs'), Var('Mid', 'list', 'NB', hyp='hMid'),
          Var('Sx', 'list', 'NB', hyp='hSx')]
    print(G.theorem('uA2', 'Unit append: back to the start of `s`.',
        '(Jl Jr s Mid Sx : List Nat) (hJl : Bits Jl) (hJr : Bits Jr) (hs : Bits s) (hMid : NoB Mid) (hSx : NoB Sx)',
        vs,
        ('U5', True, 'Jl M Jr M s M Mid B Sx M', 'M'), ('UCP', False, 'B Jl M Jr M', 's M Mid B Sx M M')))
    vs2 = [Var('Jl', 'list', 'bits', hyp='hJl'), Var('Jr', 'list', 'bits', hyp='hJr'),
           Var('u', 'list', 'bits', hyp='hu'), Var('v', 'list', 'bits', hyp='hv'),
           Var('Mid', 'list', 'NB', hyp='hMid'), Var('Sx', 'list', 'NB', hyp='hSx'),
           Var('w', 'list', 'bits', hyp='hw')]
    print(G.theorem('uBody', 'Unit append: copy one bit of `s` to the new unit (blank and restore).',
        '(Jl Jr u v Mid Sx w : List Nat) (b : Nat) (hb : b ∈ bits) (hJl : Bits Jl) (hJr : Bits Jr) (hu : Bits u) '
        '(hv : Bits v) (hMid : NoB Mid) (hSx : NoB Sx) (hw : Bits w)',
        vs2,
        ('UCP', False, 'B Jl M Jr M u', '$b v M Mid B Sx M M w'),
        ('UCP', False, 'B Jl M Jr M u $b', 'v M Mid B Sx M M w $b'),
        cases=[('b', [2, 3], 'hb')]))
    print(G.theorem('uEnd', 'Unit append: `s` copied; the final `0`, the new marker is current, back to the left end.',
        '(Jl Jr u Mid Sx w : List Nat) (hJl : Bits Jl) (hJr : Bits Jr) (hu : Bits u) (hMid : NoB Mid) (hSx : NoB Sx) '
        '(hw : Bits w)',
        [vs2[0], vs2[1], vs2[2], vs2[4], vs2[5], vs2[6]],
        ('UCP', False, 'B Jl M Jr M u', 'M Mid B Sx M M w'),
        ('UDW', False, 'B', 'Jl M Jr M u M Mid B Sx M B w 0')))
    # walker with units
    vw = [Var('Jl', 'list', 'bits', hyp='hJl'), Var('Jr', 'list', 'bits', hyp='hJr'),
          Var('R', 'list', 'ALL', hyp='hR')]
    print(G.theorem('udwStep', 'The walker steps left over the bit `j`; a unit is appended next (`U0`).',
        '(Jl Jr R : List Nat) (j : Nat) (hj : j ∈ bits) (hJl : Bits Jl) (hJr : Bits Jr) (hR : Sym4 R)',
        vw,
        ('UDW', False, 'B', 'Jl $j M Jr M R'), ('U0', False, 'B Jl M $j', 'Jr M R'),
        cases=[('j', [2, 3], 'hj')]))
    print(G.theorem('udwHome', 'The walker is home: `WB2` on the blank left of it.',
        '(Jr R : List Nat) (hJr : Bits Jr) (hR : Sym4 R)',
        [vw[1], vw[2]],
        ('UDW', False, 'B', 'M Jr M R'), ('WB2', True, 'B', 'M Jr M R')))
    print('end ZP.MH')


if __name__ == '__main__':
    main()
