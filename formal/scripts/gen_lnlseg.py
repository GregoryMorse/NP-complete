"""Generate ZP/LNLSeg.lean: the interpreter segments of the one-way verifier run of `zlnl`
(python3 formal/scripts/gen_lnlseg.py > ZP/LNLSeg.lean).

The tape of a verifier run is

    Q  0^g  0  Lw  c  H  Rw'  M_g  W  M_3  F        (Rw' = bitsOf (Rt ++ [false]): the last cell is the dummy `0`)

The zp2 segments that sweep `Lw`/`Rw` (count-down, halting peeks) are unchanged (they are about
`zlnlLogic` here); the act is new: `GH w d` on `H` looks at the cell right of `H` (`XW w d`), which is a
bit (the guest cells, or the dummy), then `d = 1` writes `w` over `H` and moves `H` left (zp2's right
move) and `d = 0` writes `w` into the blank `c` and stays."""
import re
import seggen
from seggen import Var

G = seggen.Gen('zlnlLogic', rows='zlnlLogic', logic='LogicLNL', qfiles=['LogicLNL', 'LogicBaseMH'],
               nsmap={'LogicLNL': 'QLNL', 'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.MHRun
public import ZP.LogicLNL

@[expose] public section

/-!
# `Z_LNL` verifier run: interpreter segments (generated)

Generated by `formal/scripts/gen_lnlseg.py`; do not edit. The tape of a verifier run is

    Q  0^g  0  Lw  c  H  Rw'  M_g  W  M_3  F        (Rw' = guest cells left of the head, then the dummy `0`)

The first segments are those of `ZP/Interp.lean` (count-down, halting peeks) stated for `zlnlLogic`; the
act is the one-way act of `native/zlnl.py`. All statements are about `zlnlLogic`.
-/

namespace ZP.MH

open ZP

'''


def out(s):
    print(s)


def main():
    print(HEAD)
    interp = open('ZP/Interp.lean').read() if False else open(
        __file__.replace('scripts/gen_lnlseg.py', 'ZP/Interp.lean')).read()
    for name in ['segA', 'segExh', 'segHalt', 'segShort1', 'segShort2']:
        m = re.search(r'(theorem %s .*?)\n\n' % name, interp, re.S)
        txt = m.group(1).replace('zpBase.Reach', 'zlnlLogic.Reach').replace('ivalid', 'cvalid')
        txt = txt.replace('theorem %s ' % name, 'theorem %sV ' % name)
        print(txt + '\n')
    vs = [Var('Qw', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('Lw', 'list', 'bits', hyp='hL'),
          Var('Rw', 'list', 'bits', hyp='hR'), Var('W', 'list', 'NB', hyp='hW')]
    out(G.theorem('segMv1L', 'Guest right move (`d = 1`): `FBACK` on the blank `c` to `RTW`; `H` moves left over `c` '
                  'and `w` stays right of it. The cell right of `H` is a bit `c0`.',
        '(Qw Lw Rw W : List Nat) (g r0 c0 : Nat) (h0 : r0 ∈ bits) (hc : c0 ∈ bits) (hQ : Bits Qw) (hL : Bits Lw) '
        '(hR : Bits Rw) (hW : NoB W)', vs,
        ('FBACK', True, 'Qw 1 1 $r0 g B Lw B', 'M $c0 Rw M W'),
        ('RTW', True, 'Qw 1 1 $r0', 'g B Lw M $r0 $c0 Rw M W'),
        cases=[('r0', [2, 3], 'h0'), ('c0', [2, 3], 'hc')]))
    out(G.theorem('segMv0L', 'Guest left move (`d = 0`): the head stays, `w` is written into the blank `c`.',
        '(Qw Lw Rw W : List Nat) (g r0 c0 : Nat) (h0 : r0 ∈ bits) (hc : c0 ∈ bits) (hQ : Bits Qw) (hL : Bits Lw) '
        '(hR : Bits Rw) (hW : NoB W)', vs,
        ('FBACK', True, 'Qw 1 0 $r0 g B Lw B', 'M $c0 Rw M W'),
        ('RTW', True, 'Qw 1 0 $r0', 'g B Lw $r0 M $c0 Rw M W'),
        cases=[('r0', [2, 3], 'h0'), ('c0', [2, 3], 'hc')]))
    print('end ZP.MH')


if __name__ == '__main__':
    main()
