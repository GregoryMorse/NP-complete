"""Generate ZP/LNLEraseSeg.lean: the erase loops and the end of the pair of `zlnlLogic`
(python3 formal/scripts/gen_lnlerase.py > ZP/LNLEraseSeg.lean)."""
import seggen
from seggen import Var

G = seggen.Gen('zlnlLogic', rows='zlnlLogic', logic='LogicLNL', qfiles=['LogicLNL', 'LogicBaseMH'],
               nsmap={'LogicLNL': 'QLNL', 'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.LNLUnitSeg

@[expose] public section

/-!
# Z_LNL: the erase loops (generated)

Generated by `formal/scripts/gen_lnlerase.py`; do not edit.
-/

namespace ZP.MH

open ZP

'''


def V(n, s='bits', h=None):
    return Var(n, 'list', s, hyp=h or 'h' + n)


def T(name, doc, binders, vs, a, b, **kw):
    print(G.theorem(name, doc, binders, vs, a, b, **kw))


def main():
    print(HEAD)
    A = V('A', 'ALL')
    R = V('R', 'ALL')
    bAR = '(A R : List Nat) (hA : Sym4 A) (hR : Sym4 R)'
    bc = '(A R : List Nat) (c : Nat) (hA : Sym4 A) (hR : Sym4 R) (hc : c ∈ NB)'
    qa, qx, qn = 'EAs', 'EX', 'EBs'
    T('eaNL', 'Erase loop: a non-blank cell.', bc, [A, R],
      (qa, False, 'A', '$c R'), (qa, False, 'A B', 'R'), cases=[('c', [1, 2, 3], 'hc')])
    T('eaBL', 'Erase loop: a blank cell.', bAR, [A, R],
      (qa, False, 'A', 'B R'), (qx, False, 'A B', 'R'))
    T('exNL', 'Erase loop: a non-blank cell after a blank.', bc, [A, R],
      (qx, False, 'A', '$c R'), (qa, False, 'A B', 'R'), cases=[('c', [1, 2, 3], 'hc')])
    T('exEL', 'Erase loop: two blanks, done.', '(A : List Nat) (hA : Sym4 A)', [A],
      (qx, False, 'A', ''), (qn, True, 'A', 'B'))
    T('eaEL', 'Erase loop: the end of the tape.', '(A : List Nat) (hA : Sym4 A)', [A],
      (qa, False, 'A', ''), (qn, True, 'A B', 'B'))
    T('ebBL', 'Back over an erased cell.', bAR, [A, R],
      (qn, True, 'A B', 'R'), (qn, True, 'A', 'B R'))
    T('ebML', 'Back at `M_2`: the successor of `s` follows.', bAR, [A, R],
      ('EBs', True, 'A M', 'R'), ('SINC', True, 'A', 'B R'))
    vs = [V('Jx'), V('s'), V('R', 'ALL')]
    T('ebEndL', 'The beep: the marked flag, `M_2` and `s` are erased; `JINC` follows.',
      '(Jx s R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hR : Sym4 R)', vs,
      ('EBs', True, 'M Jx M s M 0', 'R'), ('JINC', True, 'M Jx', 'M s->B B B R'))
    print('end ZP.MH')


if __name__ == '__main__':
    main()
