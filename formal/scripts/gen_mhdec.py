"""Generate ZP/MHDecSeg.lean: segments of the decider fuel and of the code copy, for `mhBase`
(python3 formal/scripts/gen_mhdec.py > ZP/MHDecSeg.lean)."""
import seggen
from seggen import Var

G = seggen.Gen('mhBase', rows='mhBase', logic='LogicBaseMH', qfiles=['LogicBaseMH'], nsmap={'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.MHUnits

@[expose] public section

/-!
# Multihead run setup: segments of the fuel blocks and of the code copy (generated)

Generated by `formal/scripts/gen_mhdec.py`; do not edit. Statements about `mhBase`.
-/

namespace ZP.MH

open ZP

/-- The symbols `1` and `M` (fuel cells and block marks). -/
def O13 : List Nat := [1, 3]
/-- The symbol `1`. -/
def T3 : List Nat := [3]
/-- The symbol `0`. -/
def Z2 : List Nat := [2]

'''


def V(n, s='bits', h=None):
    return Var(n, 'list', s, hyp=h or 'h' + n)


def main():
    print(HEAD)
    # BLK start: M at the end, back to the first bit of s
    vs = [V('Jl'), V('Jr'), V('s'), V('T', 'O13')]
    print(G.theorem('blkStart', '`BLK` starts: `M` at the end, back to the first bit of `s`.',
        '(Jl Jr s T : List Nat) (hJl : Bits Jl) (hJr : Bits Jr) (hs : Bits s) (hT : ∀ a ∈ T, a ∈ O13)', vs,
        ('GRB', False, 'Jl M Jr M s M T', ''), ('COPY', False, 'Jl M Jr M', 's M T M')))
    vs = [V('P', 'NB'), V('u'), V('v'), V('T', 'O13')]
    print(G.theorem('copyBody', 'One `COPY` round: a `1` at the far end for each bit of `s`.',
        '(P u v T : List Nat) (b : Nat) (hP : NoB P) (hu : Bits u) (hv : Bits v) (hT : ∀ a ∈ T, a ∈ O13) (hb : b ∈ bits)',
        vs, ('COPY', False, 'P u', '$b v M T M u->1'), ('COPY', False, 'P u $b', 'v M T M u->1 1'),
        cases=[('b', [2, 3], 'hb')]))
    vs = [V('Jl'), V('Jr'), V('s'), V('t', 'T3'), V('Bl', 'O13')]
    print(G.theorem('blkDecStep', 'Decider fuel block done, the walker steps right.',
        '(Jl Jr s t Bl : List Nat) (b : Nat) (hJl : Bits Jl) (hJr : Bits Jr) (hs : Bits s) (ht : ∀ a ∈ t, a ∈ T3) '
        '(hBl : ∀ a ∈ Bl, a ∈ O13) (hb : b ∈ bits)', vs,
        ('COPY', False, 'Jl M $b Jr M s', 'M M t M Bl M s->1'),
        ('GRB', False, 'Jl $b M Jr M s M M t M Bl M s->1 1', ''), cases=[('b', [2, 3], 'hb')]))
    vs = [V('Jl'), V('s'), V('t', 'T3'), V('Bl', 'O13')]
    print(G.theorem('blkDecLastU', 'Last decider fuel block: the walker is at `M_1`; the first unit is appended (`U0`).',
        '(Jl s t Bl : List Nat) (hJl : Bits Jl) (hs : Bits s) (ht : ∀ a ∈ t, a ∈ T3) (hBl : ∀ a ∈ Bl, a ∈ O13)', vs,
        ('COPY', False, 'Jl M M s', 'M M t M Bl M s->1'),
        ('U0', False, 'B Jl M M', 's M M t M Bl M s->1 1')))
    # code copy
    vs = [V('Qc'), V('Xr'), V('V', 'NB'), V('v'), V('X'), V('Rest', 'ALL')]
    print(G.theorem('qcBody', 'Code copy: one bit into `Q`.',
        '(Qc Xr V v X Rest : List Nat) (b : Nat) (hQc : Bits Qc) (hXr : Bits Xr) (hV : NoB V) (hv : Bits v) '
        '(hX : Bits X) (hRest : Sym4 Rest) (hb : b ∈ bits)', vs,
        ('QC', True, 'Qc M Xr M V v $b', 'Qc M X M Rest'), ('QC', True, '$b Qc M Xr M V v', '$b Qc M X M Rest'),
        cases=[('b', [2, 3], 'hb')]))
    vs = [V('P'), V('Xr'), V('Vq', 'NB'), V('X'), V('Rest', 'ALL')]
    print(G.theorem('qcEnd', 'Code copied: the sentinel `0`, the separator becomes the gap, one rotation.',
        '(P Xr Vq X Rest : List Nat) (hP : Bits P) (hXr : Bits Xr) (hVq : NoB Vq) (hX : Bits X) (hRest : Sym4 Rest)', vs,
        ('QC', True, 'P M Xr M Vq M', 'P M X M Rest'), ('TW', True, '0 P', 'B Xr M Vq M P M X M Rest')))
    print('end ZP.MH')


if __name__ == '__main__':
    main()
