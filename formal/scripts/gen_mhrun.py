def main():
    print(HEAD)
    vs = [Var('Qw', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('W', 'list', 'NB', hyp='hW'),
          Var('F', 'list', 'NB', hyp='hF'), Var('S', 'list', 'ALL', hyp='hS')]
    print(G.theorem('segC0', '`BK2` on the blank `c`: to the last fuel cell; the storage is right of the fuel.',
        '(Qw W F S : List Nat) (g : Nat) (hQ : Bits Qw) (hW : NoB W) (hF : NoB F) (hS : Sym4 S)', vs,
        ('BK2', True, 'Qw g B B', 'M M W M F B S'), ('DEC1', True, 'Qw g B B M M W M F', 'B S')))


if __name__ == '__main__':
    main()
