"""Generate the interpreter segments of ZP/MHSeg.lean (python3 formal/scripts/gen_mhinterp.py > ZP/MHSeg.lean).

The multihead decider has no guest cells left or right of the scanned cell `c`, so the zp2 segments
that sweep `Lw`/`Rw` are replaced by versions without them (`Lw = Rw = []`)."""
import sys
import seggen
from seggen import Var, explore

G = seggen.Gen('mhBase', rows='mhBase', logic='LogicBaseMH', qfiles=['LogicBaseMH'], nsmap={'LogicBaseMH': 'QMH'})

HEAD = '''module

public import ZP.MHInterp

@[expose] public section

/-!
# Multihead run: interpreter segments without guest cells (generated)

Generated by `formal/scripts/gen_mhinterp.py`. The tape of a multihead run is

    Q  0^g  0  c  H  M_g W ...        (c = the scanned symbol, `0` = blank, H = `1` = M)

so the zp2 segments of `ZP/Interp.lean` that sweep guest cells `Lw`/`Rw` (the count-down write, the
halting peeks, the write-and-move) are redone here for `Lw = Rw = []`; `segB`, `segC` and the token
segments of `ZP/MHInterp.lean` are unchanged. All statements are about `mhBase`.
-/

namespace ZP.MH

open ZP

'''


def out(s):
    print(s)


def main():
    print(HEAD)
    # 1. count-down on a bit
    vs = [Var('Qw', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('Wr', 'list', 'ALL', hyp='hWr')]
    out(G.theorem('segA0', 'Count-down: `BK2` on a bit `ch`, to `TW` at the right end of `Q`.',
        '(Qw Wr : List Nat) (g ch : Nat) (hch : ch ∈ bits) (hQ : Bits Qw) (hWr : Sym4 Wr)', vs,
        ('BK2', True, 'Qw g B $ch', 'M Wr'), ('TW', True, 'Qw', 'g B $cd M Wr'),
        cases=[('ch', [2, 3], 'hch')], derived={'cd': ('(cdn ch)', lambda s: 0 if s['ch'] == 2 else 2)}))
    # 2. time-out
    vs = [Var('Qw', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('W', 'list', 'ALL', hyp='hW')]
    out(G.theorem('segExh0', 'Time-out: `EXH` on the blank `c`, cleanup, result 0.',
        '(Qw W : List Nat) (g r : Nat) (hr : r ∈ bits) (hQ : Bits Qw) (hW : Sym4 W)', vs,
        ('EXH', True, 'Qw $r g B B', 'M M W'), ('DP10', False, 'M', 'W'),
        cases=[('r', [2, 3], 'hr')]))
    # 3. halting peeks: |R| >= 3 with t = 0, |R| = 1, |R| = 2
    dp = ('(dpOf %s)', lambda s: 'DP11' if s['r0'] == 3 else 'DP10')
    out(G.theorem('segHalt', 'Halting peek `w d 0`: outcome `w`.',
        '(Qw W : List Nat) (g r0 r1 : Nat) (h0 : r0 ∈ bits) (h1 : r1 ∈ bits) (hQ : Bits Qw) (hW : Sym4 W)', vs,
        ('FBACK', True, 'Qw 0 $r1 $r0 g B B', 'M M W'), (('(dpOf r0)', dp[1]), False, 'M', 'W'),
        cases=[('r0', [2, 3], 'h0'), ('r1', [2, 3], 'h1')]))
    out(G.theorem('segShort1', 'Single-entry code `[false]`: halt with outcome 0.',
        '(W : List Nat) (g : Nat) (hW : Sym4 W)', [Var('Qw', 'empty'), Var('g', 'zeros'),
                                                   Var('W', 'list', 'ALL', hyp='hW')],
        ('FBACK', True, '0 g B B', 'M M W'), ('DP10', False, 'M', 'W')))
    out(G.theorem('segShort2', 'Two-entry code `[r0, false]`: halt with outcome `r0`.',
        '(W : List Nat) (g r0 : Nat) (h0 : r0 ∈ bits) (hW : Sym4 W)', [Var('Qw', 'empty'), Var('g', 'zeros'),
                                                                     Var('W', 'list', 'ALL', hyp='hW')],
        ('FBACK', True, '0 $r0 g B B', 'M M W'), (('(dpOf r0)', dp[1]), False, 'M', 'W'),
        cases=[('r0', [2, 3], 'h0')]))
    # 4. the peek of a non-halting entry: FBACK on the blank c to GH w d on H
    vs = [Var('Qw', 'list', 'bits', hyp='hQ'), Var('g', 'zeros'), Var('Wr', 'list', 'ALL', hyp='hWr')]
    gh = ('(ghOf w d)', lambda s: 'GH%d%d' % (s['w'] - 2, s['d'] - 2))
    out(G.theorem('segPk', 'Peek of an entry `w d 1`: `FBACK` on the blank `c` to `GH w d` on `H`.',
        '(Qw Wr : List Nat) (g w d : Nat) (hw : w ∈ bits) (hdd : d ∈ bits) (hQ : Bits Qw) (hWr : Sym4 Wr)', vs,
        ('FBACK', True, 'Qw 1 $d $w g B B', 'M Wr'), (('(ghOf w d)', gh[1]), False, 'Qw 1 $d $w g B B', 'M Wr'),
        cases=[('w', [2, 3], 'hw'), ('d', [2, 3], 'hdd')]))


if __name__ == '__main__':
    main()
