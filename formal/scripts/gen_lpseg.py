"""Generate ZP/LPSeg.lean: the segments of the L = P pair that belong to `zlpLogic` only (dispatch after the units,
run setup, post-run dispatch, erase loops, `GH` step)  (python3 formal/scripts/gen_lpseg.py > ZP/LPSeg.lean)."""
import seggen
from seggen import Var

G = seggen.Gen('zlpLogic', rows='zlpLogic', logic='LogicLP', qfiles=['LogicBaseMH', 'LogicLP'],
               nsmap={'LogicBaseMH': 'QMH', 'LogicLP': 'QLP'})

HEAD = '''module

public import ZP.MHDec
public import ZP.ExtChecksMH
public import ZP.LogicLP

@[expose] public section

/-!
# Z_LP: segments of the pair that belong to `zlpLogic` (generated)

Generated by `formal/scripts/gen_lpseg.py`; do not edit.
-/

namespace ZP.MH

open ZP

'''


def V(n, s='bits', h=None):
    return Var(n, 'list', s, hyp=h or 'h' + n)


def T(name, doc, binders, vs, a, b, **kw):
    print(G.theorem(name, doc, binders, vs, a, b, **kw))


def main():
    print(HEAD)
    # ---- verifier: from the end of the fuel block to the dispatch ----
    T('blkVerLP', 'The verifier fuel is built: back to the far left, the walker home, the dispatch reads `C`.',
      '(j s C : List Nat) (hj : Bits j) (hs : Bits s) (hC : ∀ a ∈ C, a ∈ T3)',
      [V('j'), V('s'), V('C', 'T3')],
      ('COPY', False, 'M j M s', 'M 1 C M M s->1'), ('GC2', False, 'B M j M s M', '1 C M M s->1 1'))
    T('gcA', 'Verifier round on a counter `1`: it becomes `0`, a unit is appended.',
      '(Jx s C R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hC : ∀ a ∈ C, a ∈ T3) (hR : Sym4 R)',
      [V('Jx'), V('s'), V('C', 'T3'), V('R', 'ALL')],
      ('GC2', False, 'B M Jx M s M', '1 C M R'), ('U0', False, 'B M Jx M s M 0', 'C M R'))
    T('gcB', 'Verifier round: skip the used cells, the next `1` becomes `0`, a unit is appended.',
      '(Jx s Z C R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hZ : ∀ a ∈ Z, a ∈ Z2) (hC : ∀ a ∈ C, a ∈ T3) '
      '(hR : Sym4 R)',
      [V('Jx'), V('s'), V('Z', 'Z2'), V('C', 'T3'), V('R', 'ALL')],
      ('GC2', False, 'B M Jx M s M', '0 Z 1 C M R'), ('U0', False, 'B M Jx M s M 0 Z 0', 'C M R'))
    T('dispGC', 'The walker is home: the dispatch reads the field after `M_2`.',
      '(Jx s R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hR : Sym4 R)',
      [V('Jx'), V('s'), V('R', 'ALL')],
      ('WB2', True, 'B', 'M Jx M s M R'), ('GC2', False, 'B M Jx M s M', 'R'))
    T('setV', 'Verifier setup: `C` is used up; `H` and the separator are written, back to the code `s`.',
      '(Jx s Z R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hZ : ∀ a ∈ Z, a ∈ Z2) (hR : Sym4 R)',
      [V('Jx'), V('s'), V('Z', 'Z2'), V('R', 'ALL')],
      ('GC2', False, 'B M Jx M s M', '0 Z M R'), ('QC', True, 'M M M Jx M s', 'M 0 Z M R'))
    T('setD', 'Decider setup: the truth flag is read; back to the code `J`.',
      '(Jx s R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hR : Sym4 R)',
      [V('Jx'), V('s'), V('R', 'ALL')],
      ('GC2', False, 'B M Jx M s M', 'M R'), ('QC', True, 'M M M Jx', 'M s M M R'))
    # ---- the `GH` step ----
    for w in (0, 1):
        for d in (0, 1):
            nm = 'GH%d%d' % (w, d)
            g2 = 'G2%d%d' % (w, d)
            T('ghs%d%d' % (w, d), 'The step from `GH` onto the cell after `H`.',
              '(A V : List Nat) (hA : Sym4 A) (hV : Sym4 V)',
              [V('A', 'ALL'), V('V', 'ALL')],
              (nm, False, 'A', 'M V'), (g2, False, 'A M', 'V'))
    # ---- post-run, verifier ----
    for nm, y in (('vTrueM', 'M'), ('vTrue0', '0')):
        T(nm, 'The verifier accepted: the truth flag `M 1` replaces the first cells of `C`.',
          '(Jx s Y : List Nat) (hJx : Bits Jx) (hs : Bits s) (hY : Sym4 Y)',
          [V('Jx'), V('s'), V('Y', 'ALL')],
          ('DP11', False, 'M', 'Jx M s M 0 %s Y' % y), ('VA3', False, 'M Jx M s M M 1', 'Y'))
    T('vFalse', 'The verifier rejected: the truth flag `M`.',
      '(Jx s Y : List Nat) (hJx : Bits Jx) (hs : Bits s) (hY : Sym4 Y)',
      [V('Jx'), V('s'), V('Y', 'ALL')],
      ('DP10', False, 'M', 'Jx M s M 0 Y'), ('VA3', False, 'M Jx M s M M', 'Y'))
    # ---- post-run, decider ----
    vs = [V('Jx'), V('s'), V('Fu', 'ALL')]
    b3 = '(Jx s Fu : List Nat) (hJx : Bits Jx) (hs : Bits s) (hFu : Sym4 Fu)'
    T('dOk1', 'Decider output `1` agrees with the flag `1`.', b3, vs,
      ('DP11', False, 'M', 'Jx M s M M 1 M Fu'), ('EAs', True, 'M Jx M s M M', '1 M Fu'))
    T('dOk0', 'Decider output `0` agrees with the flag `0`.', b3, vs,
      ('DP10', False, 'M', 'Jx M s M M M Fu'), ('EAs', True, 'M Jx M s M M', 'M Fu'))
    T('dBad1', 'Decider output `1`, flag `0`: the beep.', b3, vs,
      ('DP11', False, 'M', 'Jx M s M M M Fu'), ('BEEP', True, 'M Jx M s M M', 'M Fu'))
    T('dBad0', 'Decider output `0`, flag `1`: the beep.', b3, vs,
      ('DP10', False, 'M', 'Jx M s M M 1 M Fu'), ('BEEP', True, 'M Jx M s M M', '1 M Fu'))
    # ---- erase loops (single steps) ----
    A = V('A', 'ALL')
    R = V('R', 'ALL')
    bAR = '(A R : List Nat) (hA : Sym4 A) (hR : Sym4 R)'
    bc = '(A R : List Nat) (c : Nat) (hA : Sym4 A) (hR : Sym4 R) (hc : c ∈ NB)'
    for (nm, qa, qx, qn) in (('e', 'EAs', 'EX', 'EBs'), ('v', 'VA3', 'EY', 'VA4')):
        T(nm + 'aN', 'Erase loop: a non-blank cell.', bc, [A, R],
          (qa, False, 'A', '$c R'), (qa, False, 'A B', 'R'), cases=[('c', [1, 2, 3], 'hc')])
        T(nm + 'aB', 'Erase loop: a blank cell.', bAR, [A, R],
          (qa, False, 'A', 'B R'), (qx, False, 'A B', 'R'))
        T(nm + 'xN', 'Erase loop: a non-blank cell after a blank.', bc, [A, R],
          (qx, False, 'A', '$c R'), (qa, False, 'A B', 'R'), cases=[('c', [1, 2, 3], 'hc')])
        T(nm + 'xE', 'Erase loop: two blanks, done.', '(A : List Nat) (hA : Sym4 A)', [A],
          (qx, False, 'A', ''), (qn, True, 'A', 'B'))
        T(nm + 'aE', 'Erase loop: the end of the tape.', '(A : List Nat) (hA : Sym4 A)', [A],
          (qa, False, 'A', ''), (qn, True, 'A B', 'B'))
        T(nm + 'bB', 'Back over an erased cell.', bAR, [A, R],
          (qn, True, 'A B', 'R'), (qn, True, 'A', 'B R'))
    T('ebM', 'Back at `M_2`: the successor of `s` follows.', bAR, [A, R],
      ('EBs', True, 'A M', 'R'), ('SINC', True, 'A', 'B R'))
    T('vbF', 'Back at the truth flag: `M_3` is written after it.',
      '(A R : List Nat) (c : Nat) (hA : Sym4 A) (hR : Sym4 R) (hc : c ∈ O13)', [A, R],
      ('VA4', True, 'A $c', 'R'), ('FB', False, 'A $c', 'R'), cases=[('c', [1, 3], 'hc')])
    T('fbW', '`M_3` after the truth flag.', '(A : List Nat) (hA : Sym4 A)', [A],
      ('FB', False, 'A', ''), ('GRB', False, 'A M', ''))
    vs = [V('Jx'), V('s'), V('R', 'ALL')]
    T('ebEnd', 'The beep: the marked flag, `M_2` and `s` are erased; `JINC` follows.',
      '(Jx s R : List Nat) (hJx : Bits Jx) (hs : Bits s) (hR : Sym4 R)', vs,
      ('EBs', True, 'M Jx M s M 0', 'R'), ('JINC', True, 'M Jx', 'M s->B B B R'))
    print('end ZP.MH')


if __name__ == '__main__':
    main()
