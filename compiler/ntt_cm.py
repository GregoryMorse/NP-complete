"""NTT-LIN machine as a counter program (mirrors ref/ntt_ref.py).

Candidate constant c lives in J and the size n in S, so the outer loop and the
test decoders are shared with Z_P.  Quasihalts iff some c gives every DFT_n over
F_p(n) a linear circuit with c*n gates.
"""
from cm import CM
from truth_cm import _K
import zp_cm


def emit_check(b, k):
    """TR := [DFT_NN over F_p has a circuit with GS gates]. NN, GS preserved."""
    r = k.r
    p, w, D, Y, Z, Q, Rm = map(r, ('p', 'w', 'D', 'Y', 'Z', 'Q', 'Rm'))
    REJ, ACC = k.lab('rej'), k.lab('acc')

    # ---- p = least prime = 1 mod n
    k.copy('NN', p)
    b.inc(p)
    PL, NOTP, ISP = k.lab('pl'), k.lab('np'), k.lab('isp')
    b.label(PL)
    Ar = r('Ar')
    k.copy(p, Ar)
    b.dec(Ar)
    b.dec(Ar, z=ISP)                    # p = 2
    b.inc(D)
    b.inc(D)
    TRI, MODL, M1, INNER, ND = (k.lab(x) for x in ('tri', 'modl', 'm1', 'in', 'nd'))
    b.label(TRI)
    b.dec(Ar, z=ISP)
    k.copy(p, Y)
    b.label(MODL)
    b.dec(Y, nz=M1, z=NOTP)
    b.label(M1)
    b.inc(Y)
    Dt = r('Dt')
    k.copy(D, Dt)
    b.label(INNER)
    b.dec(Dt, z=MODL)
    b.dec(Y, z=ND)
    b.jmp(INNER)
    b.label(ND)
    b.clear(Dt)
    b.inc(D)
    b.jmp(TRI)
    b.label(NOTP)
    b.clear(Ar)
    b.clear(D)
    k.copy('NN', p)
    b.jmp(PL)
    b.label(ISP)
    b.clear(Ar)
    b.clear(D)

    def mulmod(x, y, dst):              # dst := x * y mod p (dst 0 on entry)
        k.mul_into(x, y, Z)
        k.divmod(Z, p, Q, dst)
        b.clear(Q)

    # ---- w = least g of order exactly n
    g, t = r('g'), r('t')
    GL, OL, OD, GOOD, NEXTG = (k.lab(x) for x in ('gl', 'ol', 'od', 'good', 'ng'))
    b.label(GL)
    b.inc(g)
    b.clear(Y)
    k.copy(g, Y)                        # y = g (< p)
    b.inc(t)
    b.label(OL)
    A1, A2 = r('A1'), r('A2')
    k.copy(Y, A1)
    b.inc(A2)
    OL2 = k.lab('ol2')
    k.eq(A1, A2, yes=OD, no=OL2)
    b.label(OL2)
    Y2 = r('Y2')
    mulmod(Y, g, Y2)
    b.clear(Y)
    b.move(Y2, [Y])
    b.inc(t)
    b.jmp(OL)
    b.label(OD)
    b.clear(Y)
    k.copy('NN', A2)
    k.eq(t, A2, yes=GOOD, no=NEXTG)     # consumes t
    b.label(NEXTG)
    b.jmp(GL)
    b.label(GOOD)
    b.move(g, [w])

    # ---- B = p^n
    Bb, cnt = r('B'), r('cnt')
    b.inc(Bb)
    k.copy('NN', cnt)
    L, Dn = k.lab('bp'), k.lab('bpd')
    b.label(L)
    b.dec(cnt, z=Dn)
    b.move(Bb, [Y])
    k.mul_into(Y, p, Bb)
    b.clear(Y)
    b.jmp(L)
    b.label(Dn)

    # ---- TOT = prod_{i < GS} (n+i)^2 p^2
    TOT, m = r('TOT'), r('m')
    b.inc(TOT)
    k.copy('NN', m)
    k.copy('GS', cnt)
    L, Dn = k.lab('tot'), k.lab('totd')
    b.label(L)
    b.dec(cnt, z=Dn)
    for f in (m, m, p, p):
        b.move(TOT, [Y])
        k.mul_into(Y, f, TOT)
        b.clear(Y)
    b.inc(m)
    b.jmp(L)
    b.label(Dn)
    b.clear(m)

    # ---- routines
    NV, IDX, VEC = r('NV'), r('IDX'), r('VEC')

    def getvec():                       # VEC := node IDX's vector; IDX consumed
        Yv, Qv, Rv = r('gY'), r('gQ'), r('gR')
        k.copy(NV, Yv)
        L, Dg = k.lab('gv'), k.lab('gvd')
        b.label(L)
        b.dec(IDX, z=Dg)
        k.divmod(Yv, Bb, Qv, Rv)
        b.clear(Rv)
        b.move(Qv, [Yv])
        b.jmp(L)
        b.label(Dg)
        k.divmod(Yv, Bb, Qv, VEC)
        b.clear(Qv)
    call_get = k.subroutine('getvec', 3, getvec)

    # ---- for F = 0 .. TOT-1
    F, Fd, BJ, G, Vu, Vv, ca, cb = map(r, ('F', 'Fd', 'BJ', 'G', 'Vu', 'Vv', 'ca', 'cb'))
    FL, NEXTF = k.lab('fl'), k.lab('nf')
    b.label(FL)
    b.dec(TOT, z=REJ)
    # NV = sum_j p^j B^j for the inputs ; BJ = B^n
    b.clear(NV)
    b.clear(BJ)
    b.inc(BJ)
    Pj = r('Pj')
    b.inc(Pj)
    k.copy('NN', cnt)
    L, Dn = k.lab('in'), k.lab('ind')
    b.label(L)
    b.dec(cnt, z=Dn)
    k.mul_into(Pj, BJ, NV)
    b.move(Pj, [Y])
    k.mul_into(Y, p, Pj)
    b.clear(Y)
    b.move(BJ, [Y])
    k.mul_into(Y, Bb, BJ)
    b.clear(Y)
    b.jmp(L)
    b.label(Dn)
    b.clear(Pj)
    # gates
    k.copy(F, Fd)
    k.copy('NN', m)                     # m = n + i
    k.copy('GS', cnt)
    GLp, GD = k.lab('gate'), k.lab('gated')
    b.label(GLp)
    b.dec(cnt, z=GD)
    for dst, rad in ((IDX, m), (r('vIdx'), m), (ca, p), (cb, p)):
        b.clear(Q)
        k.divmod(Fd, rad, Q, dst)
        b.move(Q, [Fd])
    call_get(0)
    b.move(VEC, [Vu])
    b.move(r('vIdx'), [IDX])
    call_get(1)
    b.move(VEC, [Vv])
    # G = sum_t ((a du + b dv) mod p) p^t
    Pt, du, dv, s1, s2, dg = map(r, ('Pt', 'du', 'dv', 's1', 's2', 'dg'))
    b.inc(Pt)
    tcnt = r('tcnt')
    k.copy('NN', tcnt)
    L, Dn = k.lab('dig'), k.lab('digd')
    b.label(L)
    b.dec(tcnt, z=Dn)
    for vec, d in ((Vu, du), (Vv, dv)):
        b.clear(Q)
        k.divmod(vec, p, Q, d)
        b.move(Q, [vec])
    k.mul_into(ca, du, s1)
    k.mul_into(cb, dv, s1)
    b.clear(du)
    b.clear(dv)
    k.divmod(s1, p, Q, dg)
    b.clear(Q)
    k.mul_into(dg, Pt, G)
    b.clear(dg)
    b.move(Pt, [Y])
    k.mul_into(Y, p, Pt)
    b.clear(Y)
    b.jmp(L)
    b.label(Dn)
    for x in (Pt, Vu, Vv, ca, cb):
        b.clear(x)
    # NV += G * BJ ; BJ *= B
    k.mul_into(G, BJ, NV)
    b.clear(G)
    b.move(BJ, [Y])
    k.mul_into(Y, Bb, BJ)
    b.clear(Y)
    b.inc(m)
    b.jmp(GLp)
    b.label(GD)
    b.clear(Fd)
    b.clear(m)
    # rows: for k = 0..n-1, row_k = sum_t (w^k)^t p^t must be some node
    zk, row, zt, kc, jc = map(r, ('zk', 'row', 'zt', 'kc', 'jc'))
    b.inc(zk)                           # w^0
    k.copy('NN', kc)
    RL, RD = k.lab('rl'), k.lab('rd')
    b.label(RL)
    b.dec(kc, z=RD)
    b.clear(row)
    b.inc(zt)
    b.inc(Pt)
    k.copy('NN', tcnt)
    L, Dn = k.lab('rw'), k.lab('rwd')
    b.label(L)
    b.dec(tcnt, z=Dn)
    k.mul_into(zt, Pt, row)
    mulmod(zt, zk, Y)
    b.clear(zt)
    b.move(Y, [zt])
    b.move(Pt, [Y])
    k.mul_into(Y, p, Pt)
    b.clear(Y)
    b.jmp(L)
    b.label(Dn)
    b.clear(zt)
    b.clear(Pt)
    # search node j < n + GS with vector = row
    k.copy('NN', jc)
    k.copy('GS', jc)
    SL, FOUND, MISS = k.lab('sl'), k.lab('found'), k.lab('miss')
    jj = r('jj')
    b.label(SL)
    b.dec(jc, z=MISS)
    k.copy(jj, IDX)
    call_get(2)
    k.copy(row, A1)
    SN = k.lab('sn')
    k.eq(VEC, A1, yes=FOUND, no=SN)
    b.label(SN)
    b.inc(jj)
    b.jmp(SL)
    b.label(FOUND)
    b.clear(jc)
    b.clear(jj)
    mulmod(zk, w, Y)
    b.clear(zk)
    b.move(Y, [zk])
    b.jmp(RL)
    b.label(MISS)                       # this circuit fails
    b.clear(jj)
    b.clear(kc)
    b.clear(zk)
    b.clear(row)
    b.label(NEXTF)
    b.inc(F)
    b.jmp(FL)
    b.label(RD)                         # every row found
    b.label(ACC)
    b.inc('TR')
    b.label(REJ)
    for x in (p, w, Bb, TOT, F, NV, BJ, zk, row, kc, jc, jj, Y, cnt, m):
        b.clear(x)


def harness(cases):
    """Test program: for each (n, s), beep iff a circuit exists, in order."""
    b = CM()
    k = _K(b, 'nt')
    for n, s in cases:
        for _ in range(n):
            b.inc('NN')
        for _ in range(s):
            b.inc('GS')
        emit_check(b, k)
        b.clear('NN')
        b.clear('GS')
        nb = b.fresh('nb')
        b.inc('Ix')                     # case counter, visible at the beep
        b.dec('TR', z=nb)
        b.beep()
        b.label(nb)
    b.label('end')
    b.dec('Ix', nz='end', z='end')
    return b


def build(candidates=None):
    b = CM()
    k = _K(b, 'nt')
    if candidates is None:
        b.inc('J')
    else:
        b.jmp('load')
    b.label('cand')
    b.inc('S')
    b.label('inst')
    k.copy('S', 'NN')
    k.mul_into('J', 'S', 'GS')
    emit_check(b, k)
    b.clear('NN')
    b.clear('GS')
    b.dec('TR', z='bad')
    b.label('ok')
    b.inc('S')
    b.jmp('inst')
    b.label('bad')
    b.beep()
    if candidates is None:
        b.inc('J')
    else:
        b.clear('J')
        b.inc('CI')
        b.jmp('load')
    b.clear('S')
    b.jmp('cand')
    if candidates is not None:
        zp_cm._candidate_table(b, candidates)
    return b
