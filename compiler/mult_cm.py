"""MUL-LIN machine as a counter program (mirrors ref/mult_ref.py).

Quasihalts iff some multitape TM multiplies n-bit integers in time O(n).

Tape list: the 2k numbers R_1, L_1, ..., R_k, L_k live in one register LS as a
stack, top = least significant.  A number v is coded MSB first in reading order
as pairs '1 c' followed by '0'.  Popping reads bits with halvings, and pushing
iterates v's bits LSB first.
"""
from cm import CM
from truth_cm import _K
import zp_cm


def build(candidates=None, probe=False):
    """probe=True (tests only): beep with the output in V at every halt and never
    abandon a candidate."""
    b = CM()
    k = _K(b, 'mt')
    if candidates is None:
        b.inc('J')
    else:
        b.jmp('load')
    b.label('cand')
    b.inc('S')
    b.label('inst')
    # N = |s| ; skip odd N and N = 0
    b.copy('S', 'U_len')
    L, D = b.fresh('len'), b.fresh('lend')
    b.label(L)
    b.pop('U_len', D)
    b.inc('N')
    b.jmp(L)
    b.label(D)
    k.copy('N', 'Nh')
    k.halve('Nh', B='Par')
    EVEN, POS = b.fresh('even'), b.fresh('pos')
    b.dec('Par', z=EVEN)
    b.clear('Nh')
    b.jmp('ok')
    b.label(EVEN)
    k.zero_test('Nh', nz=POS, z='ok')
    b.label(POS)
    # x, y ; Want = x * y
    k.copy('S', 'U')
    b.inc('Pw')
    POP, POPPED, NB = b.fresh('pk'), b.fresh('pkd'), b.fresh('pnb')
    b.label(POP)
    b.dec('Nh', z=POPPED)
    b.pop('U', 'ok', B='bit')
    b.dec('bit', z=NB)
    k.copy('Pw', 'Y')
    b.label(NB)
    b.move('Pw', ['Pw2', 'Pw2'])
    b.move('Pw2', ['Pw'])
    b.jmp(POP)
    b.label(POPPED)
    SUB, SD = b.fresh('sub'), b.fresh('sd')
    b.label(SUB)
    b.dec('Pw', z=SD)
    b.dec('U')
    b.jmp(SUB)
    b.label(SD)                              # U = x, Y = y
    k.mul_into('U', 'Y', 'Want')
    b.clear('U')
    b.clear('Y')
    # clock T = |J| * (N + 1)
    b.copy('J', 'U_lenJ')
    L, D = b.fresh('lenJ'), b.fresh('lenJd')
    b.label(L)
    b.pop('U_lenJ', D)
    b.inc('E')
    b.jmp(L)
    b.label(D)
    b.copy('N', 'N1')
    b.inc('N1')
    k.mul_into('E', 'N1', 'Tb')
    b.clear('E')
    b.clear('N1')
    # ------------------------------------------------------------ run
    # k = entry 0 + 1 ; Pk = 4^k
    b.clear('IDX')
    lookup = _lookup(b, k)
    lookup(0)                                # -> EV, or 'bad'
    b.move('EV', ['Kt'])
    b.inc('Kt')
    b.inc('Pk')
    k.copy('Kt', 'Kc')
    L, D = b.fresh('p4'), b.fresh('p4d')
    b.label(L)
    b.dec('Kc', z=D)
    b.move('Pk', ['Pk2', 'Pk2', 'Pk2', 'Pk2'])
    b.move('Pk2', ['Pk'])
    b.jmp(L)
    b.label(D)
    pop_num, push_num = _list_ops(b, k)
    # initial tapes k..2 blank, then L_1 = 0, R_1 = enc(S)
    k.copy('Kt', 'Kc')
    b.dec('Kc')
    L, D = b.fresh('it'), b.fresh('itd')
    b.label(L)
    b.dec('Kc', z=D)
    for _ in range(2):
        b.move('LD', ['LD2', 'LD2'])
        b.move('LD2', ['LD'])
    b.jmp(L)
    b.label(D)
    push_num(0)                              # L_1 = 0 (V = 0)
    k.copy('S', 'X')
    ENC, ENCD = b.fresh('enc'), b.fresh('encd')
    b.label(ENC)                             # V := enc(X)
    b.pop('X', ENCD, B='w')
    b.move('V', ['U_enc', 'U_enc'])
    b.move('w', ['U_enc'])
    b.move('U_enc', ['V', 'V'])
    b.inc('V')
    b.jmp(ENC)
    b.label(ENCD)
    push_num(1)
    b.move('LD', ['LS'])
    # ------------------------------------------------------------ step
    b.label('mstep')
    b.dec('Tb', z='bad')                     # timeout: no output
    # pass 1: tapes 1..k from LS to LD, sym = 2 sym + (R_i mod 2)
    k.copy('Kt', 'Kc')
    P1, P1D = b.fresh('p1'), b.fresh('p1d')
    b.label(P1)
    b.dec('Kc', z=P1D)
    pop_num(0)
    b.move('V', ['V1'])                      # R_i
    pop_num(1)                               # V = L_i
    push_num(2)
    b.move('V1', ['V'])
    k.copy('V', 'Vb')
    b.move('Sym', ['Sym2', 'Sym2'])
    b.move('Sym2', ['Sym'])
    k.halve('Vb', B='Sym')
    b.clear('Vb')
    push_num(3)
    b.jmp(P1)
    b.label(P1D)
    b.move('LD', ['LS'])
    # entry 1 + O + sym
    b.inc('IDX')
    k.copy('O', 'IDX')
    b.move('Sym', ['IDX'])
    lookup(1)
    b.clear('Kn')
    b.clear('Act')
    k.divmod('EV', 'Pk', 'Kn', 'Act')
    HALT = b.fresh('mhalt')
    b.dec('Kn', z=HALT)
    b.clear('O')
    b.move('Kn', ['O'])
    # pass 2: tapes k..1 from LS to LD, action digit = Act mod 4
    k.copy('Kt', 'Kc')
    P2, P2D, RIGHT, LEFT, DONE2 = (b.fresh(x) for x in ('p2', 'p2d', 'rt', 'lf', 'dn2'))
    b.label(P2)
    b.dec('Kc', z=P2D)
    pop_num(2)
    b.move('V', ['Rr'])
    pop_num(3)
    b.move('V', ['Ll'])
    k.halve('Act', B='Wb')
    k.halve('Act', B='Db')
    b.dec('Db', nz=RIGHT, z=LEFT)
    b.label(RIGHT)                           # L = 2L + w ; R = R // 2
    b.move('Ll', ['V', 'V'])
    b.move('Wb', ['V'])
    push_num(4)
    k.halve('Rr')
    b.move('Rr', ['V'])
    push_num(5)
    b.jmp(P2)
    b.label(LEFT)                            # R = 2(2(R//2) + w) + L mod 2 ; L //= 2
    b.clear('Lb')
    k.halve('Ll', B='Lb')
    b.move('Ll', ['V'])
    push_num(6)
    k.halve('Rr')
    b.move('Rr', ['V2', 'V2'])
    b.move('Wb', ['V2'])
    b.move('V2', ['V', 'V'])
    b.move('Lb', ['V'])
    push_num(7)
    b.jmp(P2)
    b.label(P2D)
    b.move('LD', ['LS'])
    b.jmp('mstep')
    # ------------------------------------------------------------ halt: Out = R_1
    b.label(HALT)
    b.clear('Act')
    # after pass 1 the list is R_k, L_k, ..., R_1, L_1 from the top
    k.copy('Kt', 'Kc')
    b.dec('Kc')
    HL, HD = b.fresh('hl'), b.fresh('hd')
    b.label(HL)
    b.dec('Kc', z=HD)
    pop_num(5)
    b.clear('V')
    pop_num(6)
    b.clear('V')
    b.jmp(HL)
    b.label(HD)
    pop_num(4)
    b.clear('LS')
    if probe:
        b.beep()
        b.clear('V')
        b.jmp('ok_')
    # compare V with Want
    k.eq('V', 'Want', yes='mt_ok', no='bad')
    b.label('mt_ok')
    b.jmp('ok_')
    # ------------------------------------------------------------ outcomes
    b.label('bad')
    if probe:
        b.jmp('ok_')
        b.label('bad_')
    for r in ('LS', 'LD', 'V', 'Want', 'Tb', 'O', 'Kt', 'Pk', 'Sym', 'IDX', 'EV', 'Act', 'Kn'):
        b.clear(r)
    b.beep()
    if candidates is None:
        b.inc('J')
    else:
        b.clear('J')
        b.inc('CI')
        b.jmp('load')
    b.clear('S')
    b.clear('N')
    b.jmp('cand')
    b.label('ok_')
    for r in ('LS', 'LD', 'V', 'Want', 'Tb', 'O', 'Kt', 'Pk', 'Sym', 'IDX', 'EV', 'Act', 'Kn'):
        b.clear(r)
    b.label('ok')
    b.clear('N')
    b.inc('S')
    b.jmp('inst')
    if candidates is not None:
        zp_cm._candidate_table(b, candidates)
    return b


def _lookup(b, k):
    """EV := value of entry IDX of code J (IDX consumed); 'bad' if absent."""
    def body():
        b.copy('J', 'Pc')
        PARSE, BIT0, BIT1T, FOUND = (b.fresh(x) for x in ('lk', 'lk0', 'lk1', 'lkf'))
        b.label(PARSE)
        b.pop('Pc', 'lk_fail', B='w')
        b.dec('w', z=BIT0)
        b.dec('IDX', z=BIT1T)
        b.inc('IDX')
        b.jmp(PARSE)
        b.label(BIT1T)
        b.inc('EV')
        b.jmp(PARSE)
        b.label(BIT0)
        b.dec('IDX', nz=PARSE, z=FOUND)
        b.label(FOUND)
        b.clear('Pc')
    call = k.subroutine('lookup', 2, body)
    b.jmp('lk_skip')
    b.label('lk_fail')
    b.clear('IDX')
    b.clear('EV')
    b.clear('Pc')
    b.clear(k.r('rf_lookup'))
    b.jmp('bad')
    b.label('lk_skip')
    return call


def _list_ops(b, k):
    def pop_body():                          # V := pop(LS)   (V = 0 on entry)
        L, D = b.fresh('pn'), b.fresh('pnd')
        b.label(L)
        k.halve('LS', B='Pb')
        b.dec('Pb', z=D)
        k.halve('LS', B='Pcb')
        b.move('V', ['Pv2', 'Pv2'])
        b.move('Pv2', ['V'])
        b.move('Pcb', ['V'])
        b.jmp(L)
        b.label(D)
    pop_num = k.subroutine('popn', 7, pop_body)

    def push_body():                         # push(LD, V); V consumed
        b.move('LD', ['LD2', 'LD2'])
        b.move('LD2', ['LD'])
        L, D, NZ = b.fresh('pu'), b.fresh('pud'), b.fresh('punz')
        b.label(L)
        k.zero_test('V', nz=NZ, z=D)
        b.label(NZ)
        k.halve('V', B='Pc2')
        for _ in range(2):
            b.move('LD', ['LD2', 'LD2'])
            b.move('LD2', ['LD'])
        b.move('Pc2', ['LD', 'LD'])
        b.inc('LD')
        b.jmp(L)
        b.label(D)
    push_num = k.subroutine('pushn', 8, push_body)
    return pop_num, push_num
